# Define label filters exactly based on original project logic
PERSON_LABELS = {
    "person", "man", "woman", "boy", "girl", "child"
}

VEHICLE_LABELS = {
    "car", "truck", "bus",
    "motorcycle", "bike", "bicycle"
}

def filter_florence_detections(results):
    detections = results["<OD>"]
    filtered = []
    for bbox, label in zip(detections["bboxes"], detections["labels"]):
        label = label.lower().strip()
        if label in PERSON_LABELS:
            filtered.append({
                "class_id": 0,
                "class_name": "Person",
                "bbox": bbox
            })
        elif label in VEHICLE_LABELS:
            filtered.append({
                "class_id": 1,
                "class_name": "Vehicle",
                "bbox": bbox
            })
    return filtered

def bbox_to_yolo(bbox, img_width, img_height):
    x1, y1, x2, y2 = bbox
    x_center = ((x1 + x2) / 2) / img_width
    y_center = ((y1 + y2) / 2) / img_height
    width = (x2 - x1) / img_width
    height = (y2 - y1) / img_height
    return x_center, y_center, width, height

def run_example(task_prompt, image, text_input=None):
    if text_input is None:
        prompt = task_prompt
    else:
        prompt = task_prompt + text_input

    inputs = florence_processor(
        text=prompt,
        images=image,
        return_tensors="pt"
    ).to("cuda", torch.float16)

    generated_ids = florence_model.generate(
        input_ids=inputs["input_ids"].cuda(),
        pixel_values=inputs["pixel_values"].cuda(),
        max_new_tokens=1024,
        early_stopping=False,
        do_sample=False,
        num_beams=3
    )

    generated_text = florence_processor.batch_decode(
        generated_ids,
        skip_special_tokens=False
    )[0]

    parsed_answer = florence_processor.post_process_generation(
        generated_text,
        task=task_prompt,
        image_size=(image.width, image.height)
    )
    return parsed_answer

